def clean_name(name):
    return name.replace("___", " ").replace("__", " ").replace("_", " ")

def predict_disease(image):
    if image is None:
        return """
        <div class="empty-box">
            <div class="empty-icon">🌿</div>
            <h2>No diagnosis yet</h2>
            <p>Upload a clear plant leaf image and click Diagnose.</p>
        </div>
        """

    img = cv2.resize(image, (128, 128))
    img = img / 255.0
    img = np.expand_dims(img, axis=0)

    prediction = model.predict(img, verbose=0)
    class_index = np.argmax(prediction)
    disease_key = encoder.inverse_transform([class_index])[0]
    confidence = float(np.max(prediction) * 100)

    disease_name = clean_name(disease_key)

    info = disease_info.get(disease_key, {
        "severity": "Needs Review",
        "color": "#f59e0b",
        "emoji": "🟡",
        "score": max(20, int(confidence)),
        "causes": "The model detected signs of disease, but detailed information is not available for this class.",
        "actions": "Upload a clearer image, isolate suspicious leaves, and monitor the plant condition."
    })

    warning = ""
    if confidence < 70:
        warning = """
        <div class="warning">
            ⚠️ Low confidence prediction. Please upload a clearer leaf image.
        </div>
        """

    return f"""
    <div class="result-card">
        <div class="badge" style="background:{info['color']}">
            {info['emoji']} {info['severity']}
        </div>

        <p class="small-title">AI Diagnosis Result</p>
        <h1>{disease_name}</h1>

        <div class="metrics">
            <div class="metric-card">
                <p>Confidence</p>
                <h2>{confidence:.2f}%</h2>
            </div>

            <div class="metric-card">
                <p>Health Score</p>
                <h2>{info['score']} / 100</h2>
            </div>
        </div>

        <div class="info-section">
            <h3>🔍 Possible Causes</h3>
            <p>{info['causes']}</p>
        </div>

        <div class="info-section">
            <h3>✅ Recommended Actions</h3>
            <p>{info['actions']}</p>
        </div>

        {warning}
    </div>
    """

